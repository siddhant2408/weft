import assert from 'node:assert/strict';
let settings;
globalThis.chrome = { storage: { local: { get: async () => ({ settings }) } } };
const { ask } = await import('../providers.js');
const serve = body => { globalThis.fetch = async () => new Response(body); };
settings = { provider: 'openai', openai: { model: 'test', baseUrl: 'https://example.com/v1' } };
const chunk = 'data: {"choices":[{"delta":{"content":"partial"}}]}\n\n';
serve(chunk);
let r = await ask({ system: 'S', prompt: 'P' });
assert.equal(r.ok, false, 'EOF without [DONE] must not succeed');
assert.equal(r.code, 'INCOMPLETE');
serve(chunk + 'data: [DONE]\n\n');
assert.equal((await ask({ system: 'S', prompt: 'P' })).text, 'partial');
serve(chunk + 'data: {"choices":[{"delta":{},"finish_reason":"length"}]}\n\ndata: [DONE]\n\n');
assert.equal((await ask({ system: 'S', prompt: 'P' })).code, 'INCOMPLETE');
settings = { provider: 'anthropic', anthropic: { apiKey: 'fake' } };
const delta = 'data: {"type":"content_block_delta","delta":{"type":"text_delta","text":"partial"}}\n\n';
serve(delta);
assert.equal((await ask({ system: 'S', prompt: 'P' })).code, 'INCOMPLETE');
serve(delta + 'data: {"type":"message_delta","delta":{"stop_reason":"max_tokens"}}\n\ndata: {"type":"message_stop"}\n\n');
assert.equal((await ask({ system: 'S', prompt: 'P' })).code, 'INCOMPLETE');
serve(delta + 'data: {"type":"message_stop"}\n\n');
assert.equal((await ask({ system: 'S', prompt: 'P' })).text, 'partial');
console.log('stream-completion: all passed');
